"""Run 5: does ANY temporal binning of the bag beat Arm A?

Run: ./surf/Scripts/python.exe -m reports.run5_binning

Section 5.4's Arm A-M result is open to one obvious objection: A-M has 9,672 columns against
Arm A's 828, under a `colsample_bytree` chosen for 828, so "of course it got worse, you changed
the feature count 11.7x". Run 5 answers that by sweeping the binning instead of jumping to the
finest one:

    828 columns  (Arm A, 1 bin)  ->  1,632 (2 six-month bins)  ->  3,240 (4 three-month bins)
                                 ->  9,672 (12 monthly bins)

All four are re-aggregations of the SAME sparse matrix by a 0/1 pooling matrix, verified exact
(agg_ctrl reproduces the dense Arm A features at max abs difference 0, and the 12->4, 12->2 and
4->2 poolings agree to 0). Same vocabulary, same exclusions, same untuned XGBoost configuration,
same ladder, seeds and test set. Two time bins is also the design used by the closest comparison
work, so A-2 is the like-for-like baseline.

Deltas are bootstrapped paired on patients, reusing reports/paired_bootstrap.py.

Writes reports/run5_binning_arthritis.md and .csv.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from src.scale.config import EXPERIMENTS, REPORTS
from reports.paired_bootstrap import (N_BOOT, RNG_SEED, _boot_metrics, _sorted_view,
                                      _stratified_counts)

DISEASE = "arthritis"
RUNGS = [100000, 300000, 1114144]
# variant -> (label, columns is read from metrics)
VARIANTS = [("agg_ctrl", "Arm A (1 bin, sparse control)"),
            ("bin2", "Arm A-2 (two 6-month bins)"),
            ("bin4", "Arm A-4 (four 3-month bins)"),
            ("monthly", "Arm A-M (twelve 1-month bins)")]


def _load(sub, size):
    base = EXPERIMENTS / DISEASE / sub
    ds = sorted(d for d in base.glob(f"size{size}_seed*") if (d / "preds.parquet").exists())
    if not ds:
        return None, None, None
    cols, y, order, nf = [], None, None, None
    for d in ds:
        p = pd.read_parquet(d / "preds.parquet")
        if order is None:
            order, y = p["PAT_ID"].to_numpy(), p["y"].to_numpy().astype(int)
        elif not np.array_equal(p["PAT_ID"].to_numpy(), order):
            raise SystemExit(f"PAT_ID order differs in {d}")
        cols.append(p["p"].to_numpy())
        nf = json.loads((d / "metrics.json").read_text()).get("n_features", nf)
    return np.column_stack(cols), y, nf


def _seed_mean(P, y):
    ones = np.ones(y.size, dtype=np.int32)
    r = np.array([_boot_metrics(_sorted_view(P[:, k], y), ones) for k in range(P.shape[1])])
    return float(r[:, 0].mean()), float(r[:, 1].mean())


def build():
    rng = np.random.default_rng(RNG_SEED)
    P, y, nf = {}, None, {}
    for sub, _ in VARIANTS:
        for s in RUNGS:
            M, yy, k = _load(f"armA_monthly/{sub}", s)
            if M is None:
                continue
            P[(sub, s)] = M; nf[(sub, s)] = k; y = yy if y is None else y
    for arm, sub in (("A", "armA/rich_full"), ("C", "armC")):
        for s in RUNGS:
            M, yy, _ = _load(sub, s)
            if M is not None:
                P[(arm, s)] = M
    pt = {k: _seed_mean(v, y) for k, v in P.items()}

    views = {k: [_sorted_view(v[:, i], y) for i in range(v.shape[1])] for k, v in P.items()}
    dist = {(k, m): np.empty(N_BOOT) for k in P for m in ("auroc", "auprc")}
    print(f"[run5] bootstrapping {len(P)} cells x {N_BOOT}...", flush=True)
    for b, c in enumerate(_stratified_counts(y, rng, N_BOOT)):
        for k, vs in views.items():
            r = np.array([_boot_metrics(v, c[v[0]]) for v in vs])
            dist[(k, "auroc")][b] = r[:, 0].mean()
            dist[(k, "auprc")][b] = r[:, 1].mean()
        if (b + 1) % 500 == 0:
            print(f"  {b+1}/{N_BOOT}", flush=True)

    def ci(a, bk, s, metric):
        d = dist[((a, s), metric)] - dist[((bk, s), metric)]
        mi = 0 if metric == "auroc" else 1
        obs = pt[(a, s)][mi] - pt[(bk, s)][mi]
        lo, hi = np.percentile(d, [2.5, 97.5])
        return obs, lo, hi, bool(lo > 0 or hi < 0)

    L = []; w = L.append; rows = []
    w("# Run 5: does any temporal binning of the bag beat Arm A?")
    w("")
    w(f"_Generated by `reports/run5_binning.py`. {N_BOOT:,} paired bootstrap resamples of the "
      "held-out patients. All binnings are exact re-aggregations of one sparse matrix; the "
      "1-bin control reproduces the dense Arm A features at max abs difference 0._")
    w("")
    for metric, lab in (("auroc", "AUROC"), ("auprc", "AUPRC")):
        w(f"## {lab}: each binning minus Arm A (dense), 95% CI")
        w("")
        w("| rung | " + " | ".join(l for _, l in VARIANTS[1:]) + " |")
        w("|---|" + "---|" * (len(VARIANTS) - 1))
        for s in RUNGS:
            cells = []
            for sub, _ in VARIANTS[1:]:
                if (sub, s) not in pt or ("A", s) not in pt:
                    cells.append("n/a"); continue
                o, lo, hi, sig = ci(sub, "A", s, metric)
                cells.append(f"{o:+.4f} [{lo:+.4f}, {hi:+.4f}]" + ("" if sig else " n.s."))
                rows.append(dict(rung=s, metric=metric, variant=sub, vs="A", diff=o,
                                 lo=lo, hi=hi, excludes_zero=sig,
                                 n_features=nf.get((sub, s))))
            w(f"| {s:,} | " + " | ".join(cells) + " |")
        w("")
    pd.DataFrame(rows).to_csv(REPORTS / f"run5_binning_{DISEASE}.csv", index=False)

    w("## Column count versus performance")
    w("")
    w("| rung | 828 (Arm A) | 1,632 (A-2) | 3,240 (A-4) | 9,672 (A-M) | monotone? |")
    w("|---|---|---|---|---|---|")
    for s in RUNGS:
        vals = [pt[("A", s)][0]] + [pt[(v, s)][0] for v, _ in VARIANTS[1:] if (v, s) in pt]
        mono = all(vals[i] >= vals[i + 1] for i in range(len(vals) - 1))
        w(f"| {s:,} | " + " | ".join(f"{v:.4f}" for v in vals) + f" | {'yes' if mono else 'no'} |")
    w("")
    w("## Reading it")
    w("")
    top = RUNGS[-1]
    best = max(VARIANTS[1:], key=lambda t: pt[(t[0], top)][0])
    w(f"- **No binning beats Arm A on AUROC at any rung.** The best of them at the top rung is "
      f"{best[1]} at {pt[(best[0], top)][0]:.4f} against Arm A's {pt[('A', top)][0]:.4f}.")
    w("- Performance degrades monotonically with binning at the two largest rungs, so the "
      "penalty is a smooth dose-response rather than a cliff at the finest binning. Crucially "
      "it is already present at **A-2, which has only twice Arm A's column count**, which is "
      "the direct answer to the objection that A-M's deficit is an artefact of an 11.7x "
      "increase in features.")
    w("- **The two effects remain confounded by construction**: finer binning necessarily means "
      "more columns, so this sweep shows the penalty grows with binning granularity without "
      "isolating whether the mechanism is temporal dilution or feature-count regularisation. "
      "What it does establish is the claim the paper needs: giving the order-free bag temporal "
      "resolution never helps, at any granularity from two bins to twelve.")
    ap = {v: ci(v, "A", top, "auprc") for v, _ in VARIANTS[1:] if (v, top) in pt}
    pos = {v: t for v, t in ap.items() if t[0] > 0}
    if pos:
        w(f"- **On AUPRC the picture is weaker and must be reported as such.** At the top rung "
          + ", ".join(f"{v} is {t[0]:+.4f} [{t[1]:+.4f}, {t[2]:+.4f}]"
                      + ("" if t[3] else ", not distinguishable from zero")
                      for v, t in pos.items())
          + ". Coarse binning is therefore roughly neutral on the precision-recall metric even "
            "where it costs AUROC, and we do not claim it harms both.")
    (REPORTS / f"run5_binning_{DISEASE}.md").write_text("\n".join(L), encoding="utf-8")
    print(f"[run5] wrote reports/run5_binning_{DISEASE}.md")


if __name__ == "__main__":
    build()
