"""Deployable operating points and the Arm A feature-set ablations (arthritis).

Run: ./surf/Scripts/python.exe -m reports.operating_points

Two things the paper quotes that had no committed source:
  1. Section 2.1's health-relevance operating points. AUROC and AUPRC are not what a health
     system acts on; precision, recall and number-needed-to-screen at a chosen alert budget are.
  2. Section 4's `thin` and `rich_noutil` feature-set ablations, which section 3 describes.
     `rich_noutil` is the answer to "you are only predicting healthcare access", since it drops
     every utilisation and recency feature.

Both are computed from the committed top-rung predictions, seed by seed then averaged, matching
how every other number in the paper is produced.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from src.scale.config import EXPERIMENTS, REPORTS

DISEASE, TOP = "arthritis", 1114144
FRACS = (0.01, 0.02, 0.05, 0.10, 0.20)


def build():
    ds = sorted((EXPERIMENTS / DISEASE / "armA" / "rich_full").glob(f"size{TOP}_seed*"))
    P = np.column_stack([pd.read_parquet(d / "preds.parquet")["p"].to_numpy() for d in ds])
    y = pd.read_parquet(ds[0] / "preds.parquet")["y"].to_numpy().astype(int)
    n, npos = len(y), int(y.sum())
    base = npos / n

    L = []
    w = L.append
    w("# Operating points and Arm A feature-set ablations")
    w("")
    w(f"_Generated by `reports/operating_points.py` from the committed top-rung Arm A "
      f"predictions ({len(ds)} seeds). Test set {n:,} patients, {npos:,} incident "
      f"({100*base:.2f}%)._")
    w("")
    w("## 1. Operating points (section 2.1)")
    w("")
    w("AUROC and AUPRC are not what a health system acts on. At a chosen alert budget:")
    w("")
    w("| flag top | patients flagged | cases caught | precision | lift over base rate | "
      "recall | reviewed per case |")
    w("|---|---|---|---|---|---|---|")
    for f in FRACS:
        k = int(n * f)
        pr, rc = [], []
        for j in range(P.shape[1]):
            idx = np.argsort(-P[:, j])[:k]
            c = y[idx].sum()
            pr.append(c / k); rc.append(c / npos)
        p_, r_ = float(np.mean(pr)), float(np.mean(rc))
        w(f"| {100*f:.0f}% | {k:,} | {p_*k:,.0f} | {100*p_:.1f}% | {p_/base:.1f}x | "
          f"{100*r_:.1f}% | {1/p_:.0f} |")
    w("")
    w("The lift quoted here is **enrichment at an alert budget**, which is not the same "
      "quantity as the AUPRC-to-base-rate ratio quoted in section 4.1. The latter summarises "
      "the whole precision-recall curve; the former is what a fixed-capacity review programme "
      "would actually experience. Both are reported because they answer different questions.")
    w("")

    a = pd.read_csv(REPORTS / f"stage6_{DISEASE}_armA_results.csv")
    g = a.groupby(["featureset", "size"]).auroc.mean().unstack(0)
    gp = a.groupby(["featureset", "size"]).auprc.mean().unstack(0)
    w("## 2. Arm A feature-set ablations (section 3)")
    w("")
    w("`thin` is the original 27 features (demographics, comorbidity flags, utilisation "
      "counts). `rich_noutil` is the full 828 minus every utilisation and recency feature, so "
      "it isolates clinical content from healthcare-access signal. `rich_full` is the arm "
      "reported everywhere else.")
    w("")
    w("| training patients | thin (27) | rich_noutil (815) | rich_full (828) |")
    w("|---|---|---|---|")
    for sz in g.index:
        w(f"| {sz:,} | {g.thin_full[sz]:.4f} | {g.rich_noutil[sz]:.4f} | {g.rich_full[sz]:.4f} |")
    w("")
    w("Same, AUPRC:")
    w("")
    w("| training patients | thin (27) | rich_noutil (815) | rich_full (828) |")
    w("|---|---|---|---|")
    for sz in gp.index:
        w(f"| {sz:,} | {gp.thin_full[sz]:.4f} | {gp.rich_noutil[sz]:.4f} | "
          f"{gp.rich_full[sz]:.4f} |")
    w("")
    t = g.loc[TOP]; tp = gp.loc[TOP]
    w(f"At the top rung, enrichment beyond the original 27 features is worth "
      f"**{t.rich_full - t.thin_full:+.4f} AUROC** and **{tp.rich_full - tp.thin_full:+.4f} "
      f"AUPRC**. Removing utilisation and recency costs "
      f"**{t.rich_full - t.rich_noutil:+.4f} AUROC** and "
      f"**{tp.rich_full - tp.rich_noutil:+.4f} AUPRC**, which bounds the share of Arm A's "
      f"performance attributable to healthcare-access intensity rather than clinical content. "
      f"At {t.rich_noutil:.4f}, the access-stripped feature arm still leads the Transformer's "
      f"{0.8063:.4f}.")
    (REPORTS / f"operating_points_{DISEASE}.md").write_text("\n".join(L), encoding="utf-8")
    print(f"wrote reports/operating_points_{DISEASE}.md")


if __name__ == "__main__":
    build()
