"""Run 1 analysis: does monthly resolution close the gap? (Arm A-M)

Run: ./surf/Scripts/python.exe -m reports.armAM_analysis

Claims are month granular and within-month order is arbitrary, so the only information the
sequence arms hold that the order-free bag lacks is which of the 12 observation months an
event fell in. Arm A-M gives the bag exactly that. If A-M closes the A-minus-C gap, the
paper's conclusion changes from "learned sequence representations do not yet pay off" to
"the benefit is temporal resolution, which a bag model can also have".

Two A-M variants are compared, for reasons that matter:
  monthly   the 9,672-column binned matrix. This is Arm A-M.
  agg_ctrl  the same matrix pooled back to Arm A's 828 columns, verified to reproduce the
            Arm A feature values exactly (max abs difference 0.0). It exists because XGBoost
            treats structural zeros in a CSR as MISSING rather than zero, so `agg_ctrl` vs
            the committed dense Arm A isolates that semantic difference, and `monthly` vs
            `agg_ctrl` is then a clean binning contrast.

Writes reports/armAM_arthritis.md and reports/armAM_arthritis.csv.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from src.scale.config import EXPERIMENTS, REPORTS
from reports.paired_bootstrap import (N_BOOT, RNG_SEED, _boot_metrics, _sorted_view,
                                      _stratified_counts)
from reports.scaling_analysis import _gap_fit, _powerlaw

DISEASE = "arthritis"
SRC = {
    "A":       "armA/rich_full",
    "B":       "armB",
    "C":       "armC",
    "A-M":     "armA_monthly/monthly",
    "A-agg":   "armA_monthly/agg_ctrl",
}


def _load(sub: str, size: int):
    base = EXPERIMENTS / DISEASE / sub
    dirs = sorted(d for d in base.glob(f"size{size}_seed*") if (d / "preds.parquet").exists())
    if not dirs:
        return None, None
    cols, y, order = [], None, None
    for d in dirs:
        p = pd.read_parquet(d / "preds.parquet")
        if order is None:
            order, y = p["PAT_ID"].to_numpy(), p["y"].to_numpy().astype(int)
        elif not np.array_equal(p["PAT_ID"].to_numpy(), order):
            raise SystemExit(f"PAT_ID order differs in {d}")
        cols.append(p["p"].to_numpy())
    return np.column_stack(cols), y


def _seed_mean(P, y):
    a, p = [], []
    ones = np.ones(y.size, dtype=np.int32)
    for k in range(P.shape[1]):
        v = _sorted_view(P[:, k], y)
        x, z = _boot_metrics(v, ones[v[0]])
        a.append(x); p.append(z)
    return float(np.mean(a)), float(np.mean(p))


def build():
    sizes = json.loads((Path("data/splits") / f"{DISEASE}_ladder_meta.json").read_text())["sizes"]
    preds, y = {}, None
    for name, sub in SRC.items():
        preds[name] = {}
        for s in sizes:
            P, yy = _load(sub, s)
            if P is not None:
                preds[name][s] = P
                y = yy if y is None else y
    have = {n: sorted(v) for n, v in preds.items()}
    print("loaded:", {n: len(v) for n, v in have.items()})
    if not preds["A-M"]:
        raise SystemExit("no Arm A-M runs found")

    pt = {(n, s): _seed_mean(preds[n][s], y) for n in preds for s in preds[n]}

    L = []
    w = L.append
    w("# Run 1: does monthly resolution close the gap? (Arm A-M)")
    w("")
    w("_Generated by `reports/armAM_analysis.py`. Arm A-M is Arm A with every count feature "
      "split into 12 monthly bins (9,672 columns), same vocabulary, same exclusions, same "
      "untuned XGBoost configuration, same ladder, seeds and test set._")
    w("")

    # ---- 1. sparse/missing semantics check ---------------------------------
    w("## 1. Control: does the sparse code path reproduce Arm A?")
    w("")
    w("XGBoost treats structural zeros in a CSR as *missing* rather than zero, so the "
      "aggregated control is run through the identical sparse path as A-M. Its feature "
      "values were verified to reproduce Arm A exactly (max abs difference 0.0 over 828 "
      "columns), so any difference below is due to that semantic change alone.")
    w("")
    w("| training patients | Arm A (dense) | A-agg (sparse, same features) | delta |")
    w("|---|---|---|---|")
    for s in sizes:
        if ("A", s) in pt and ("A-agg", s) in pt:
            a, g = pt[("A", s)][0], pt[("A-agg", s)][0]
            w(f"| {s:,} | {a:.4f} | {g:.4f} | {g-a:+.4f} |")
    w("")

    # ---- 2. learning curves -------------------------------------------------
    w("## 2. Learning curves (AUROC, seed mean)")
    w("")
    order = [n for n in ("A", "A-M", "C", "B") if preds[n]]
    w("| training patients | " + " | ".join(order) + " | A-M minus A | A-M minus C |")
    w("|---|" + "---|" * (len(order) + 2))
    for s in sizes:
        if not all((n, s) in pt for n in order):
            continue
        cells = [f"{pt[(n, s)][0]:.4f}" for n in order]
        w(f"| {s:,} | " + " | ".join(cells)
          + f" | {pt[('A-M', s)][0]-pt[('A', s)][0]:+.4f}"
          + f" | {pt[('A-M', s)][0]-pt[('C', s)][0]:+.4f} |")
    w("")
    w("AUPRC at the same rungs:")
    w("")
    w("| training patients | " + " | ".join(order) + " |")
    w("|---|" + "---|" * len(order))
    for s in sizes:
        if not all((n, s) in pt for n in order):
            continue
        w(f"| {s:,} | " + " | ".join(f"{pt[(n, s)][1]:.4f}" for n in order) + " |")
    w("")

    # ---- 3. paired bootstrap ------------------------------------------------
    print("[armAM] bootstrapping...", flush=True)
    rng = np.random.default_rng(RNG_SEED)
    pairs = [("A-M", "A"), ("A-M", "C"), ("A-M", "B"), ("A-agg", "A")]
    usable = [s for s in sizes if all((n, s) in pt for p in pairs for n in p)]
    views = {(n, s): [_sorted_view(preds[n][s][:, k], y)
                      for k in range(preds[n][s].shape[1])]
             for n in SRC for s in usable if (n, s) in pt}
    dist = {(n, s, m): np.empty(N_BOOT) for n in SRC for s in usable
            for m in ("auroc", "auprc") if (n, s) in pt}
    for b, c in enumerate(_stratified_counts(y, rng, N_BOOT)):
        for (n, s), vs in views.items():
            r = np.array([_boot_metrics(v, c[v[0]]) for v in vs])
            dist[(n, s, "auroc")][b] = r[:, 0].mean()
            dist[(n, s, "auprc")][b] = r[:, 1].mean()
        if (b + 1) % 500 == 0:
            print(f"  {b+1}/{N_BOOT}", flush=True)

    rows = []
    w("## 3. Paired bootstrap on the same patients (95% CI)")
    w("")
    for metric, lab in (("auroc", "AUROC"), ("auprc", "AUPRC")):
        w(f"### {lab}")
        w("")
        w("| training patients | " + " | ".join(f"{a} - {b}" for a, b in pairs) + " |")
        w("|---|" + "---|" * len(pairs))
        for s in usable:
            cells = []
            for a, b in pairs:
                d = dist[(a, s, metric)] - dist[(b, s, metric)]
                obs = pt[(a, s)][0 if metric == "auroc" else 1] - \
                      pt[(b, s)][0 if metric == "auroc" else 1]
                lo, hi = np.percentile(d, [2.5, 97.5])
                ns = "" if (lo > 0 or hi < 0) else " n.s."
                cells.append(f"{obs:+.4f} [{lo:+.4f}, {hi:+.4f}]{ns}")
                rows.append(dict(size=s, metric=metric, pair=f"{a}-{b}", diff=obs,
                                 lo=lo, hi=hi, excludes_zero=bool(lo > 0 or hi < 0)))
            w(f"| {s:,} | " + " | ".join(cells) + " |")
        w("")
    pd.DataFrame(rows).to_csv(REPORTS / f"armAM_{DISEASE}.csv", index=False)

    # ---- 4. power law -------------------------------------------------------
    w("## 4. Saturating power-law fit for Arm A-M")
    w("")
    w("| arm | fit window | ceiling | exponent | at top rung | headroom |")
    w("|---|---|---|---|---|---|")
    for name in ("A", "A-M"):
        ss = np.array([s for s in sizes if (name, s) in pt])
        vv = np.array([pt[(name, s)][0] for s in ss])
        for lo, lab in ((ss[0], "all rungs"), (30000, "excl. 10k")):
            m = ss >= lo
            f = _powerlaw(ss[m], vv[m])
            if f["identified"]:
                w(f"| {name} | {lab} | {f['ceiling']:.4f} | {f['exponent']:.3f} | "
                  f"{vv[-1]:.4f} | {f['ceiling']-vv[-1]:+.4f} |")
            else:
                w(f"| {name} | {lab} | not identifiable | | {vv[-1]:.4f} | |")
    w("")
    for hi_a, lo_a in (("A-M", "C"), ("A", "C")):
        ss = np.array([s for s in sizes if (hi_a, s) in pt and (lo_a, s) in pt])
        g = np.array([pt[(hi_a, s)][0] - pt[(lo_a, s)][0] for s in ss])
        m = ss >= 30000
        sl, par = _gap_fit(ss[m], g[m])
        w(f"- **{hi_a} vs {lo_a}** (excl. 10k): gap closes {sl:+.4f} per decade, "
          f"extrapolated parity at n = {par:.2e}.")
    w("")

    # ---- 5. verdict ---------------------------------------------------------
    top = max(usable)
    dam = pt[("A-M", top)][0] - pt[("A", top)][0]
    damc = pt[("A-M", top)][0] - pt[("C", top)][0]
    w("## 5. Verdict")
    w("")
    if dam >= 0.002:
        w(f"- Monthly resolution **helps** the bag model (+{dam:.4f} AUROC at the top rung). "
          "The paper's framing must change: part of what the sequence arms provide is "
          "temporal binning, obtainable without representation learning.")
    elif dam <= -0.002:
        w(f"- Monthly resolution **does not help and slightly hurts** the bag model "
          f"({dam:+.4f} AUROC at the top rung). Handing Arm A the one piece of information "
          "the sequence arms hold does not close the gap, so the gap is not explained by "
          "temporal resolution.")
    else:
        w(f"- Monthly resolution is **neutral** for the bag model ({dam:+.4f} AUROC at the "
          "top rung).")
    w(f"- Arm A-M still leads the Transformer by **{damc:+.4f} AUROC** at the top rung.")
    w("")
    w("**Caveat that must be stated.** A-M has 11.7x the feature count of Arm A under an "
      "identical, untuned XGBoost configuration (same depth, same 800-round cap, same "
      "`colsample_bytree=0.8`). Sampling 80% of 9,672 columns is a very different "
      "regularisation regime from 80% of 828. So the correct claim is that monthly "
      "resolution does not help **under matched, untuned hyperparameters**, not that it "
      "cannot help. A retuned A-M is the obvious follow-up and was deliberately not run, "
      "because retuning only the arm we want to help would break the parity rule.")
    (REPORTS / f"armAM_{DISEASE}.md").write_text("\n".join(L), encoding="utf-8")
    print(f"[armAM] wrote reports/armAM_{DISEASE}.md")


if __name__ == "__main__":
    build()
